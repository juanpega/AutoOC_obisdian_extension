// scripts/inline-visual-builder.mjs
//
// Reads `util/ui_workflow_builder/index.html` and writes the content to
// `visualBuilderHtml.generated.ts` as a string constant. The TypeScript
// file is `require`'d by `main.ts`, so the HTML ships inside `main.js`
// and the extension has no file-system or path-resolution dependencies
// at runtime.
//
// This script is invoked automatically by `npm run build` and
// `npm run dev` via the `prebuild` / `predev` lifecycle hooks.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const htmlPath = path.join(repoRoot, "util", "ui_workflow_builder", "index.html");
const outPath = path.join(repoRoot, "visualBuilderHtml.generated.ts");

if (!fs.existsSync(htmlPath)) {
  console.error("incoming HTML not found at", htmlPath);
  process.exit(1);
}

const html = fs.readFileSync(htmlPath, "utf8");
// Escape backticks, backslashes, and template-literal placeholders so
// the HTML can be safely embedded in a template literal.
const escaped = html
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

const banner =
`// THIS FILE IS GENERATED BY scripts/inline-visual-builder.mjs.
// DO NOT EDIT BY HAND. Run \`npm run prebuild\` (or any build/dev
// command) to regenerate.

export const visualBuilderHtml: string =
`;

const content = banner + "`" + escaped + "`;\n";

fs.writeFileSync(outPath, content, "utf8");
console.log("Wrote", outPath, "(" + content.length + " bytes)");
